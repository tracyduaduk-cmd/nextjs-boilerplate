export async function fetchProjects(): Promise<ProjectRecord[]> {
  try {
    const { data: projectsData, error: projectsError } = await supabase
      .from("projects")
      .select("*")
      .order("sort_order", { ascending: true });

    if (projectsError || !projectsData || projectsData.length === 0) {
      console.warn("Supabase project query notice, using fallback projects:", projectsError?.message);
      return attachMediaToProjects(FALLBACK_PROJECTS, FALLBACK_PROJECT_MEDIA);
    }

    const { data: mediaData } = await supabase
      .from("project_media")
      .select("*")
      .order("sort_order", { ascending: true });

    const mediaList = (mediaData && mediaData.length > 0) ? (mediaData as ProjectMediaRecord[]) : FALLBACK_PROJECT_MEDIA;

    return attachMediaToProjects(projectsData as ProjectRecord[], mediaList);
  } catch (err) {
    console.warn("Error fetching projects from Supabase, returning fallback dataset:", err);
    return attachMediaToProjects(FALLBACK_PROJECTS, FALLBACK_PROJECT_MEDIA);
  }
}

export async function fetchProjectBySlug(slug: string): Promise<ProjectRecord | null> {
  const projects = await fetchProjects();
  const project = projects.find((p) => p.slug === slug);
  return project || null;
}

function attachMediaToProjects(
  projects: ProjectRecord[],
  media: ProjectMediaRecord[]
): ProjectRecord[] {
  return projects.map((proj) => {
    const projMedia = media.filter((m) => m.project_id === proj.id);
    return {
      ...proj,
      media: projMedia.length > 0 ? projMedia : FALLBACK_PROJECT_MEDIA.filter((m) => m.project_id === proj.id),
    };
  });
}
